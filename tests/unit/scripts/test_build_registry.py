import json

from neurosim.common.evalkit import EvalSpec
from scripts.build_registry import HEADER, load_results, render_registry


def spec(eval_id: str, **overrides) -> EvalSpec:
    fields = {
        "id": eval_id,
        "claim": "claim text",
        "reference": "reference text",
        "metric": "metric text",
        "threshold": "< 1",
        "seeds": (0,),
        "area": eval_id.split("-")[1].lower(),
    }
    return EvalSpec(**{**fields, **overrides})


def test_render_registry_lists_every_eval_sorted_with_its_status():
    specs = {
        "E-FUS-002": spec("E-FUS-002", seeds=(0, 1)),
        "E-CT-001": spec("E-CT-001", claim="|HU| of water\nis small"),
        "E-FUS-001": spec("E-FUS-001"),
    }
    results = {
        "E-CT-001": {"value": 0.123456789, "passed": True},
        "E-FUS-002": {"value": {"max_error": 2.5, "n_bad": 3.0}, "passed": False},
        "E-HEAD-009": {"value": 1.0, "passed": True},
    }
    lines = render_registry(specs, results).splitlines()

    assert lines[0] == "# Eval registry"
    assert lines[2] == HEADER == "Generated by scripts/build_registry.py. Do not edit by hand."
    assert lines[4] == (
        "| ID | Claim | Reference | Metric | Threshold | Seeds | Status | Last value |"
    )
    assert lines[5] == "|---|---|---|---|---|---|---|---|"
    assert lines[6:] == [
        "| E-CT-001 | \\|HU\\| of water is small | reference text | metric text | < 1 | 0 "
        "| passing | 0.123457 |",
        "| E-FUS-001 | claim text | reference text | metric text | < 1 | 0 | not built |  |",
        "| E-FUS-002 | claim text | reference text | metric text | < 1 | 0, 1 | failing "
        "| max_error=2.5, n_bad=3 |",
    ]


def test_load_results_reads_result_files_by_id(tmp_path):
    record = {"id": "E-CT-001", "value": 0.5, "passed": True, "note": "", "git_commit": "unknown"}
    (tmp_path / "E-CT-001.json").write_text(json.dumps(record))
    (tmp_path / "notes.txt").write_text("ignored")
    assert load_results(tmp_path) == {"E-CT-001": record}
    assert load_results(tmp_path / "missing") == {}
