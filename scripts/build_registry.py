"""Regenerate ``evals/REGISTRY.md`` from the registered evals and their latest results.

Usage: ``python scripts/build_registry.py``. Imports every eval module (which
fills ``neurosim.common.evalkit.REGISTRY``), reads ``evals/results/*.json`` and
writes the table. An eval without a result file is listed as "not built".
"""

from __future__ import annotations

import importlib
import json
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from neurosim.common import evalkit

REPO_ROOT = Path(__file__).resolve().parents[1]
EVALS_DIR = REPO_ROOT / "evals"
REGISTRY_PATH = EVALS_DIR / "REGISTRY.md"
HEADER = "Generated by scripts/build_registry.py. Do not edit by hand."
COLUMNS = ("ID", "Claim", "Reference", "Metric", "Threshold", "Seeds", "Status", "Last value")


def import_eval_modules() -> None:
    """Import every ``evals/<area>/test_e_*.py`` so that its eval registers itself."""
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    for path in sorted(EVALS_DIR.glob("*/test_e_*.py")):
        importlib.import_module(".".join(path.relative_to(REPO_ROOT).with_suffix("").parts))


def load_results(results_dir: Path) -> dict[str, dict[str, Any]]:
    """Read the result files written by ``evalkit.report``, keyed by eval id."""
    return {
        path.stem: json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(results_dir.glob("E-*.json"))
    }


def status_of(result: Mapping[str, Any] | None) -> str:
    """Return the registry status for a result record (``None`` if the eval has not run)."""
    if result is None:
        return "not built"
    return "passing" if result["passed"] else "failing"


def _format_value(value: float | Mapping[str, float]) -> str:
    if isinstance(value, Mapping):
        return ", ".join(f"{name}={number:.6g}" for name, number in value.items())
    return f"{value:.6g}"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_registry(
    specs: Mapping[str, evalkit.EvalSpec], results: Mapping[str, Mapping[str, Any]]
) -> str:
    """Return the markdown text of the registry: one row per eval, sorted by id."""
    rows = []
    for eval_id in sorted(specs):
        spec = specs[eval_id]
        result = results.get(eval_id)
        rows.append(
            (
                spec.id,
                spec.claim,
                spec.reference,
                spec.metric,
                spec.threshold,
                ", ".join(str(seed) for seed in spec.seeds),
                status_of(result),
                "" if result is None else _format_value(result["value"]),
            )
        )
    lines = [
        "# Eval registry",
        "",
        HEADER,
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "---|" * len(COLUMNS),
    ]
    lines += ["| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def main() -> None:
    import_eval_modules()
    results = load_results(evalkit.RESULTS_DIR)
    REGISTRY_PATH.write_text(render_registry(evalkit.REGISTRY, results), encoding="utf-8")
    counts = {"passing": 0, "failing": 0, "not built": 0}
    for eval_id in evalkit.REGISTRY:
        counts[status_of(results.get(eval_id))] += 1
    summary = ", ".join(f"{count} {status}" for status, count in counts.items())
    target = REGISTRY_PATH.relative_to(REPO_ROOT)
    print(f"wrote {target}: {len(evalkit.REGISTRY)} evals ({summary})")


if __name__ == "__main__":
    main()
