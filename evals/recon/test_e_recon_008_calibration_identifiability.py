"""E-RECON-008: without model mismatch, calibration brings the delays closer to the truth.

Synthetic scenes whose skull is exactly a phase screen (`recon.synthetic`, the
dataset of configs/recon_small.yaml): the data are generated by the model the
calibration fits, so what is measured is identifiability through the image
prior, not model error. The CT screen (50 ns rms delay error, -0.3 Np amplitude
bias) is the starting point; the truth is the screen that generated the data.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from neurosim.common.config import from_dict, load_yaml
from neurosim.common.evalkit import REGISTRY, eval_case, report
from neurosim.common.seeding import SeedTree
from neurosim.fus.config import imaging_setup
from neurosim.recon.calibrate import calibrate_screen
from neurosim.recon.checkpoint import DEFAULT_PRIOR_PATH, load_prior
from neurosim.recon.config import ReconConfig
from neurosim.recon.forward import scene_screen_model
from neurosim.recon.metrics import delay_error
from neurosim.recon.seeding import configure_torch
from neurosim.recon.synthetic import synthetic_run

EVAL_ID = "E-RECON-008"
STREAM_SUB = 1008
CONFIG = Path(__file__).resolve().parents[2] / "configs" / "recon_small.yaml"
MAX_MEDIAN_RATIO = 0.7
MAX_RATIO = 1.0


@eval_case(
    id=EVAL_ID,
    claim="On data generated by the phase-screen model itself, the calibrated per-element "
    "delays (gauge removed) are closer to the true delays than the CT starting point",
    reference="The screen that generated the synthetic data (recon.synthetic); no model mismatch",
    metric="ratio = rms delay error of the calibrated screen / rms delay error of the CT screen "
    "(common delay and tilt removed), per scene; median and maximum over five scene seeds "
    "(configs/recon_small.yaml: 48 elements, 30 trials, trained prior, default calibration)",
    threshold="median ratio < 0.7 and every ratio < 1.0 (fixed before this eval was run, after "
    "development runs on two other scenes gave ratios of 0.55 and 0.93: the starting error of "
    "50 ns is a tenth of the 500 ns period, and 0.7 brings it to a fourteenth, the Marechal "
    "criterion for a diffraction-limited focus (Strehl ratio 0.8); a calibration that makes "
    "any scene worse than its starting point is not usable unattended)",
    seeds=(10, 11, 12, 13, 14),
)
def test_e_recon_008_calibration_identifiability():
    if not DEFAULT_PRIOR_PATH.is_file():
        pytest.fail(
            f"{EVAL_ID} needs the trained prior at {DEFAULT_PRIOR_PATH}; create it with "
            "scripts/make_prior_dataset.py and scripts/train_prior.py (configs/prior_default.yaml)"
        )
    cfg = from_dict(ReconConfig, load_yaml(CONFIG))
    configure_torch(cfg.num_threads)
    prior = load_prior(DEFAULT_PRIOR_PATH)
    ratios, amplitude_errors = {}, {}
    for seed in REGISTRY[EVAL_ID].seeds:
        tree = SeedTree(seed)
        scene, trials = synthetic_run(cfg.synthetic, tree)
        transducer = imaging_setup(scene.imaging).transducer
        element_x = transducer.element_x()
        result = calibrate_screen(
            prior,
            scene_screen_model(scene, cfg.calibration.source_refinement),
            scene.screen_ct,
            element_x,
            transducer.center_frequency,
            trials.power_doppler["skull_das"].mean(axis=0),
            scene.noise_floor["skull_das"],
            scene.cell_area,
            scene.effective_frames * len(trials.label),
            cfg.calibration,
            tree,
            STREAM_SUB,
        )
        errors = [
            delay_error(screen.delays, scene.screen_true.delays, element_x, cfg.calibration.gauge)
            for screen in (result.screen, scene.screen_ct)
        ]
        ratios[f"ratio_seed_{seed}"] = errors[0] / errors[1]
        amplitude_errors[f"log_amplitude_error_seed_{seed}"] = float(
            np.mean(np.log(result.screen.amplitudes) - np.log(scene.screen_true.amplitudes))
        )

    median, worst = float(np.median(list(ratios.values()))), float(max(ratios.values()))
    report(
        EVAL_ID,
        {"median_ratio": median, "max_ratio": worst, **ratios, **amplitude_errors},
        passed=median < MAX_MEDIAN_RATIO and worst < MAX_RATIO,
        note="log_amplitude_error_seed_* is the mean log-amplitude error of the calibrated "
        "screen [Np]; the CT screen starts at -0.3",
    )
